"""List, without touching anything, the scripts of the `tools/` folder of each repository that nothing uses.

    python tools/vendored_tools_report.py [--workspace FOLDER] [--write docs/VENDORED_TOOLS_REPORT.md]

A script of `tools/` (not a test, not a `__init__.py`) is *used* when the workflow files of `.github/workflows`, a script of the
root (run / build / test / dev scripts, the manifest, Cargo.toml, package.json, pyproject.toml, build.rs) or another used script
of `tools/` names it (by file name or by module name). Tests, documents and scripts that nobody uses are only listed as what
refers to it. The report says what is not reached; it never deletes, and a person decides what to do with each line.
With --write the report is written as a Markdown document that can be generated again; without it, it is printed."""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import version_places as vp  # noqa: E402

HUB = Path(__file__).resolve().parents[1]
CODE_SUFFIXES = {".py", ".sh", ".bat", ".ps1", ".cmd", ".js", ".mjs"}
ROOT_SCRIPT_SUFFIXES = {".sh", ".bat", ".ps1", ".cmd", ".vbs"}
ROOT_SCRIPT_NAMES = {"Makefile", "justfile", "build.rs", "eh3d.project.json", "package.json", "pyproject.toml", "Cargo.toml"}


def read(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def mentions(text: str, tool: Path) -> bool:
    if tool.name in text:
        return True
    return re.search(r"(?<![\w-])%s(?![\w-])" % re.escape(tool.stem), text) is not None


def analyse(root: Path) -> dict:
    """{"tools": [names], "used": [...], "unreached": {name: [what refers to it]}} for one repository."""
    folder = root / "tools"
    tools = sorted(p for p in folder.glob("*") if p.is_file() and p.suffix in CODE_SUFFIXES and not p.name.startswith("test_") and p.name != "__init__.py") if folder.is_dir() else []
    tests = [p for p in (sorted(folder.glob("test_*.py")) if folder.is_dir() else [])] + [p for p in sorted((root / "tests").rglob("*.py")) if (root / "tests").is_dir()]
    workflow = [p for p in sorted((root / ".github" / "workflows").glob("*.y*ml"))] if (root / ".github" / "workflows").is_dir() else []
    scripts = [p for p in sorted(root.glob("*")) if p.is_file() and (p.suffix in ROOT_SCRIPT_SUFFIXES or p.name in ROOT_SCRIPT_NAMES)]
    docs = [p for p in sorted(root.glob("*.md"))] + [p for p in sorted((root / "docs").rglob("*.md"))] if (root / "docs").is_dir() else sorted(root.glob("*.md"))
    entry_text = "\n".join(read(p) for p in workflow + scripts)
    tool_text = {p: read(p) for p in tools}
    used = {p for p in tools if mentions(entry_text, p)}
    queue = list(used)
    while queue:
        current = queue.pop()
        for other in tools:
            if other not in used and other != current and mentions(tool_text[current], other):
                used.add(other)
                queue.append(other)
    test_text, doc_text = {p: read(p) for p in tests}, {p: read(p) for p in docs}
    unreached: dict[str, list[str]] = {}
    for tool in tools:
        if tool in used:
            continue
        by = []
        if any(mentions(t, tool) for t in test_text.values()):
            by.append("tests")
        by += [f"tool {o.name}" for o in tools if o != tool and mentions(tool_text[o], tool)]
        if any(mentions(t, tool) for t in doc_text.values()):
            by.append("documents")
        unreached[tool.name] = by
    return {"tools": [p.name for p in tools], "used": sorted(p.name for p in used), "unreached": unreached}


def report(workspace: Path) -> tuple[str, int]:
    """(the Markdown document, the number of tools that nothing reaches)."""
    repos = [p for p in sorted(workspace.glob("EH3D-*")) if (p / vp.MANIFEST).is_file() and p.resolve() != HUB.resolve()]
    results = {p.name: analyse(p) for p in repos}
    total = sum(len(r["unreached"]) for r in results.values())
    lines = [
        "# Vendored tools that nothing uses",
        "",
        "Generated by `python tools/vendored_tools_report.py --write docs/VENDORED_TOOLS_REPORT.md`; regenerate it instead of editing it. "
        "It lists, for each repository next to this one, the scripts of its `tools/` folder that no workflow, no run / build / test script, "
        "no manifest and no other used script names. Nothing is deleted: a person looks at each line and decides.",
        "",
        "A script counts as used when a workflow file, a script of the root of the repository (or its manifest, `Cargo.toml`, "
        "`package.json`, `pyproject.toml`) or a script of `tools/` that is itself used names it by file or module name. "
        "A name can be matched by chance, so the list errs on the side of calling a script used.",
        "",
        "## Summary",
        "",
        f"{len(repos)} repositories were read; {total} scripts are not reached.",
        "",
        "| Repository | Scripts in `tools/` | Used | Not reached |",
        "|---|---|---|---|",
    ]
    for name, r in results.items():
        lines.append(f"| {name} | {len(r['tools'])} | {len(r['used'])} | {len(r['unreached'])} |")
    lines += ["", "## Scripts that are not reached", ""]
    if not total:
        lines.append("None.")
    for name, r in results.items():
        if not r["unreached"]:
            continue
        lines += [f"### {name}", "", "| Script | Still named by |", "|---|---|"]
        for tool, by in sorted(r["unreached"].items()):
            lines.append(f"| `{tool}` | {', '.join(by) if by else 'nothing'} |")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n", total


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="The scripts of tools/ that nothing in the repository uses (a report; nothing is deleted).")
    parser.add_argument("--workspace", type=Path, help="the folder that holds the repositories (default: the parent of this repository)")
    parser.add_argument("--write", type=Path, help="write the report as a Markdown file instead of printing it")
    args = parser.parse_args(argv)
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    text, total = report(args.workspace or HUB.parent)
    if args.write:
        target = args.write if args.write.is_absolute() else HUB / args.write
        target.write_bytes(text.encode("utf-8"))
        print(f"wrote {target.name}: {total} scripts are not reached")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
